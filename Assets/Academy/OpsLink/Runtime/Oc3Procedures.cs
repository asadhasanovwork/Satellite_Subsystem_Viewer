    /// <summary>
    /// Script Runner procedures for every Academy satellite, modelled on the AZERSAT demo procedures
    /// (health check, startup, eclipse, solar arrays, manoeuvre) but generated from the satellite's own
    /// dictionary: each procedure only uses the telemetry and commands this design really has.
    /// </summary>
    public static class Oc3Procedures
    {
        public static readonly string[] FileNames =
        {
            "health_check.rb", "startup_sequence.rb", "eclipse_pass.rb", "solar_array_ops.rb", "maneuver_ops.rb"
        };

        static readonly CultureInfo Ci = CultureInfo.InvariantCulture;

        /// <summary>Writes the procedures into targets/&lt;T&gt;/procedures.</summary>
        public static void Write(Oc3Dictionary d, string procedureDir)
        {
            Directory.CreateDirectory(procedureDir);
            var g = new Gen(d);
            File.WriteAllText(Path.Combine(procedureDir, "health_check.rb"), g.HealthCheck());
            File.WriteAllText(Path.Combine(procedureDir, "startup_sequence.rb"), g.Startup());
            File.WriteAllText(Path.Combine(procedureDir, "eclipse_pass.rb"), g.Eclipse());
            File.WriteAllText(Path.Combine(procedureDir, "solar_array_ops.rb"), g.SolarArrays());
            File.WriteAllText(Path.Combine(procedureDir, "maneuver_ops.rb"), g.Maneuver());
        }

        sealed class Gen
        {
            readonly Oc3Dictionary _d;
            readonly string _t;
            readonly Dictionary<string, (Oc3TlmPacket p, Oc3Item i)> _num = new Dictionary<string, (Oc3TlmPacket, Oc3Item)>();
            readonly Dictionary<string, (Oc3TlmPacket p, Oc3Item i)> _txt = new Dictionary<string, (Oc3TlmPacket, Oc3Item)>();

            public Gen(Oc3Dictionary d)
            {
                _d = d;
                _t = d.TargetName;
                foreach (Oc3TlmPacket p in d.Telemetry)
                    foreach (Oc3Item i in p.Items)
                    {
                        if (string.IsNullOrEmpty(i.Key)) continue;
                        var map = i.Type == Oc3Type.String ? _txt : _num;
                        if (!map.ContainsKey(i.Key)) map[i.Key] = (p, i);
                    }
            }

            // ------------------------------------------------------------------ lookups

            string Num(string key) => _num.TryGetValue(key, out var v) ? $"{_t} {v.p.Name} {v.i.Name}" : null;
            string Txt(string key) => _txt.TryGetValue(key, out var v) ? $"{_t} {v.p.Name} {v.i.Name}" : null;
            /// <summary>Readable form of a point: its text twin when it has one, else the number.</summary>
            string Show(string key) => Txt(key) ?? Num(key);

            IEnumerable<string> NumKeys(Func<string, bool> pred) => _num.Keys.Where(pred).OrderBy(k => k, StringComparer.Ordinal);
            IEnumerable<string> TxtKeys(Func<string, bool> pred) => _txt.Keys.Where(pred).OrderBy(k => k, StringComparer.Ordinal);

            Oc3Command Cmd(string simTarget, string simCommand) =>
                _d.Commands.FirstOrDefault(c => string.Equals(c.SimTarget, simTarget, StringComparison.OrdinalIgnoreCase) &&
                                                string.Equals(c.SimCommand, simCommand, StringComparison.OrdinalIgnoreCase));
            IEnumerable<Oc3Command> Cmds(Func<Oc3Command, bool> pred) => _d.Commands.Where(c => c.SimTarget != null && pred(c));

            string C(Oc3Command c, string args = null) => $"{_t} {c.Name}" + (string.IsNullOrEmpty(args) ? "" : " with " + args);

            static string Q(string s) => (s ?? "").Replace("\\", "\\\\").Replace("\"", "\\\"");
            static string N(double v) => v.ToString("0.###", Ci);

            /// <summary>Thruster sets (with tanks) as (component id, OpenC3 command prefix).</summary>
            List<string> ThrusterSets() =>
                Cmds(c => c.SimCommand == "BURN").Select(c => c.SimTarget).Distinct().ToList();

            // ------------------------------------------------------------------ shared Ruby

            string Header(string title, string what)
            {
                var sb = new StringBuilder();
                sb.Append("# encoding: utf-8\n");
                sb.Append($"# {_d.SatelliteName}: {title}\n");
                sb.Append($"# {what}\n");
                sb.Append("# Generated by Satellite Academy for this satellite's own hardware (adapted from the AZERSAT demo procedures).\n");
                sb.Append("# Copy it to your own file before editing: it is rewritten when the satellite is flown again.\n\n");
                sb.Append($"TARGET = \"{_t}\"\n\n");
                sb.Append(Helpers);
                return sb.ToString();
            }

            const string Helpers = @"# ---- helpers -----------------------------------------------------------------
$issues = []
$warnings = []

def ok(label, value)
  puts ""    ✅ #{label}: #{value}""
end

def warn_item(label, value, reason = nil)
  puts ""    ⚠️  #{label}: #{value}#{reason ? "" — #{reason}"" : """"}""
  $warnings << ""#{label}: #{value}""
end

def fail_item(label, value, reason = nil)
  puts ""    ❌ #{label}: #{value}#{reason ? "" — #{reason}"" : """"}""
  $issues << ""#{label}: #{value}""
end

def num(v)
  v.is_a?(Numeric) && !(v.respond_to?(:nan?) && v.nan?)
end

def fmt(v, unit = nil, dec = 2)
  return 'no data' unless num(v)
  unit ? ""#{v.round(dec)} #{unit}"" : v.round(dec).to_s
end

# Green / yellow / red check. Yellow starts 10 % before the red limit, like the OpenC3 limits.
def check_value(label, value, lo: nil, hi: nil, unit: nil, dec: 2)
  unless num(value)
    warn_item(label, 'no data', 'no telemetry received yet (contact?)')
    return
  end
  ylo = lo ? lo + 0.1 * lo.abs : nil
  yhi = hi ? hi - 0.1 * hi.abs : nil
  text = fmt(value, unit, dec)
  if (lo && value < lo) || (hi && value > hi)
    fail_item(label, text, 'out of limits')
  elsif (ylo && value < ylo) || (yhi && value > yhi)
    warn_item(label, text, 'close to the limit')
  else
    ok(label, text)
  end
end

def section(title)
  puts """"
  puts title
  puts ""  "" + ""─"" * [title.length, 4].max
end

def contact?
  tlm(""#{TARGET} SIM_STATUS CONTACT"").to_f > 0.5
end

# Commands only reach the satellite during a ground-station pass.
def wait_for_contact(timeout = 1800)
  return true if contact?
  aos = tlm(""#{TARGET} SIM_STATUS NEXT_AOS_IN"").to_f
  puts ""  📡 No contact. Next pass in #{aos.round} s (simulation time). Waiting...""
  puts ""     Tip: SIM_SET_WARP speeds the simulation up.""
  return true if wait(""#{TARGET} SIM_STATUS CONTACT == 1"", timeout)
  puts ""  ❌ Still no contact after #{timeout} s.""
  false
end

# Sends a command and prints the satellite's answer (CMD_ACK).
def send_cmd(command)
  before = tlm(""#{TARGET} CMD_ACK COUNT"").to_i
  cmd(command)
  if wait(""#{TARGET} CMD_ACK COUNT > #{before}"", 10)
    ok_flag = tlm(""#{TARGET} CMD_ACK ACCEPTED"").to_f > 0.5
    puts ""    #{ok_flag ? '↳' : '✗'} #{tlm(""#{TARGET} CMD_ACK RESULT"")}""
    ok_flag
  else
    puts ""    ✗ no answer from the satellite (contact?)""
    false
  end
end

def met
  tlm(""#{TARGET} SIM_STATUS MET"").to_f
end

# Waits for a number of simulation seconds (follows SIM_SET_WARP).
def wait_sim(seconds)
  stop = met + seconds
  loop do
    break if met >= stop
    wait(1)
  end
end

";

            // ------------------------------------------------------------------ 1. health check

            public string HealthCheck()
            {
                var sb = new StringBuilder(Header("health check", "Full subsystem report: every telemetry point against its limits, then HEALTHY / DEGRADED / CRITICAL."));
                sb.Append("puts \"🛰️  #{TARGET} health check\"\n");
                sb.Append("puts \"  MET #{met.round} s | contact: #{contact? ? 'YES' : 'NO'} | telemetry age #{tlm(\"#{TARGET} SIM_STATUS TLM_AGE\").round} s\"\n");
                sb.Append("puts \"  (Out of contact the values are from the last pass.)\" unless contact?\n");

                int n = 1;
                foreach (Oc3TlmPacket p in _d.Telemetry.Where(x => x.Id < Oc3Dictionary.IdSimStatus))
                {
                    var nums = p.Items.Where(i => i.Type != Oc3Type.String).ToList();
                    if (nums.Count == 0) continue;
                    sb.Append($"\nsection(\"{n++}. {Q(p.Description)}\")\n");
                    foreach (Oc3Item i in nums)
                    {
                        string label = Q(string.IsNullOrEmpty(i.Description) ? i.Name : i.Description);
                        string unit = string.IsNullOrWhiteSpace(i.Unit) ? "nil" : $"\"{Q(i.Unit)}\"";
                        Oc3Item twin = p.Items.FirstOrDefault(x => x.Type == Oc3Type.String && x.Key == i.Key);
                        if (twin != null)
                        {
                            // state point: show the text; a few states mean trouble
                            sb.Append($"v = tlm(\"{_t} {p.Name} {twin.Name}\").to_s\n");
                            sb.Append($"if v =~ /FAIL|FAULT|ERROR|OFFLINE|SAFE MODE|TUMBL/i then fail_item(\"{label}\", v) ");
                            sb.Append($"elsif v =~ /STOWED|NO DATA|INVALID|LOST/i then warn_item(\"{label}\", v) ");
                            sb.Append($"else ok(\"{label}\", v) end\n");
                            continue;
                        }
                        string lo = double.IsNaN(i.Low) ? "nil" : N(i.Low);
                        string hi = double.IsNaN(i.High) ? "nil" : N(i.High);
                        if (lo == "nil" && hi == "nil")
                            sb.Append($"ok(\"{label}\", fmt(tlm(\"{_t} {p.Name} {i.Name}\"), {unit}, {Math.Min(i.Decimals, 3)}))\n");
                        else
                            sb.Append($"check_value(\"{label}\", tlm(\"{_t} {p.Name} {i.Name}\"), lo: {lo}, hi: {hi}, unit: {unit}, dec: {Math.Min(i.Decimals, 3)})\n");
                    }
                }

                sb.Append(@"
# ---- summary -----------------------------------------------------------------
puts """"
puts ""═"" * 48
puts ""  Health check summary""
if $issues.empty? && $warnings.empty?
  puts ""  ✅ All systems nominal""
else
  unless $issues.empty?
    puts ""  ❌ CRITICAL (#{$issues.length}):""
    $issues.each { |i| puts ""     • #{i}"" }
  end
  unless $warnings.empty?
    puts ""  ⚠️  WARNINGS (#{$warnings.length}):""
    $warnings.each { |w| puts ""     • #{w}"" }
  end
end
overall = $issues.empty? ? ($warnings.empty? ? 'HEALTHY' : 'DEGRADED') : 'CRITICAL'
puts ""\n  Overall: #{overall}""
puts ""═"" * 48
");
                return sb.ToString();
            }

            // ------------------------------------------------------------------ 2. startup

            public string Startup()
            {
                var sb = new StringBuilder(Header("startup sequence (LEOP)",
                    "After separation: contact, deploy, detumble, Sun-safe, battery charge, heaters, nominal mode, payload."));
                string soc = Num("eps.battery.soc");
                string rate = Num("adcs.rate");
                string mode = Show("adcs.mode");
                string obsw = Show("obsw.mode");
                string temp = Num("tcs.temperature");
                Oc3Command adcsMode = Cmd("ADCS", "MODE");

                sb.Append("puts \"🚀 #{TARGET} startup sequence\"\n");
                sb.Append("\n# Step 1: contact and first look\nputs \"\\n🔍 Step 1: contact and first look\"\n");
                sb.Append("exit unless wait_for_contact\n");
                sb.Append($"puts \"  ADCS: #{{{(mode != null ? $"tlm(\"{mode}\")" : "'-'")}}} | OBSW: #{{{(obsw != null ? $"tlm(\"{obsw}\")" : "'-'")}}}\"\n");
                if (soc != null) sb.Append($"puts \"  Battery: #{{fmt(tlm(\"{soc}\"), '%', 1)}}\"\n");
                if (rate != null) sb.Append($"puts \"  Body rate: #{{fmt(tlm(\"{rate}\"), 'deg/s', 3)}}\"\n");

                // Deploy mechanisms
                var deploys = Cmds(c => c.SimCommand == "DEPLOY").ToList();
                if (deploys.Count > 0)
                {
                    sb.Append("\n# Step 2: deploy solar arrays and antennas\nputs \"\\n⚡ Step 2: deployment\"\n");
                    foreach (Oc3Command c in deploys)
                    {
                        string state = Show(c.SimTarget.ToLowerInvariant() + ".deployed");
                        if (state != null)
                            sb.Append($"if tlm(\"{state}\").to_s =~ /YES|DEPLOYED|1/i\n  puts \"  {c.SimTarget} already deployed\"\nelse\n");
                        else sb.Append("begin\n");
                        sb.Append($"  puts \"  Firing {c.SimTarget} (hazardous: confirm in the dialog)\"\n");
                        sb.Append($"  send_cmd(\"{C(c)}\")\n");
                        if (state != null) sb.Append($"  10.times {{ break if tlm(\"{state}\").to_s =~ /YES|DEPLOYED/i; wait(3) }}\n  puts \"  {c.SimTarget}: #{{tlm(\"{state}\")}}\"\n");
                        sb.Append("end\n");
                    }
                }

                foreach (Oc3Command c in Cmds(c => c.SimCommand == "ON" && c.SimTarget.Contains("sada")))
                    sb.Append($"\nputs \"\\n☀️  Solar array drive on\"\nsend_cmd(\"{C(c)}\")\n");

                if (adcsMode != null)
                {
                    sb.Append("\n# Step 3: detumble, then point the arrays at the Sun\nputs \"\\n🎯 Step 3: detumble → Sun-safe\"\n");
                    sb.Append($"send_cmd(\"{C(adcsMode, "OPTION DETUMBLE")}\")\n");
                    if (rate != null)
                    {
                        sb.Append("limit = met + 3600\n");
                        sb.Append($"while num(tlm(\"{rate}\")) && tlm(\"{rate}\") > 0.3 && met < limit\n");
                        sb.Append($"  puts \"  rate #{{fmt(tlm(\"{rate}\"), 'deg/s', 3)}} — damping...\"\n  wait_sim(60)\nend\n");
                        sb.Append($"puts \"  ✅ rate #{{fmt(tlm(\"{rate}\"), 'deg/s', 3)}}\"\n");
                    }
                    sb.Append($"send_cmd(\"{C(adcsMode, "OPTION SUNSAFE")}\")\n");
                }

                if (soc != null)
                {
                    sb.Append("\n# Step 4: charge the battery\nputs \"\\n🔋 Step 4: battery to 50 %\"\n");
                    sb.Append("limit = met + 6 * 3600\n");
                    sb.Append($"while num(tlm(\"{soc}\")) && tlm(\"{soc}\") < 50.0 && met < limit\n");
                    sb.Append($"  puts \"  battery #{{fmt(tlm(\"{soc}\"), '%', 1)}} — charging...\"\n  wait_sim(300)\nend\n");
                    sb.Append($"puts \"  Battery: #{{fmt(tlm(\"{soc}\"), '%', 1)}}\"\n");
                }

                var heaters = Cmds(c => c.SimCommand == "ON" && c.SimTarget.StartsWith("tcs.")).ToList();
                if (heaters.Count > 0)
                {
                    sb.Append("\n# Step 5: thermal control\nputs \"\\n🌡️ Step 5: heaters on\"\n");
                    foreach (Oc3Command c in heaters) sb.Append($"send_cmd(\"{C(c)}\")\n");
                    if (temp != null) sb.Append($"puts \"  Internal temperature: #{{fmt(tlm(\"{temp}\"), 'C', 1)}}\"\n");
                }

                Oc3Command nominal = Cmd("OBSW", "NOMINAL");
                if (nominal != null)
                {
                    sb.Append("\n# Step 6: nominal mode\nputs \"\\n✅ Step 6: OBSW nominal\"\n");
                    sb.Append($"send_cmd(\"{C(nominal)}\")\n");
                    if (obsw != null) sb.Append($"puts \"  OBSW mode: #{{tlm(\"{obsw}\")}}\"\n");
                }

                var payloads = Cmds(c => c.SimCommand == "ON" && c.SimTarget.StartsWith("pl.")).ToList();
                if (payloads.Count > 0)
                {
                    sb.Append("\n# Step 7: payload\nputs \"\\n🛰️ Step 7: payload on\"\n");
                    sb.Append("if message_box('Switch the payload on now?', 'Yes', 'No') == 'Yes'\n");
                    foreach (Oc3Command c in payloads) sb.Append($"  send_cmd(\"{C(c)}\")\n  wait(1)\n");
                    sb.Append("end\n");
                }

                sb.Append("\nputs \"\\n🛰️  Startup complete. Run health_check.rb for the full report.\"\n");
                return sb.ToString();
            }

            // ------------------------------------------------------------------ 3. eclipse

            public string Eclipse()
            {
                var sb = new StringBuilder(Header("eclipse pass",
                    "Follows the satellite through the next real Earth shadow: solar power, battery, temperature."));
                string sun = Show("orbit.sun");
                string sunNum = Num("orbit.sun");
                string soc = Num("eps.battery.soc");
                string gen = Num("eps.generation");
                string net = Num("eps.net");
                string temp = Num("tcs.temperature");
                if (sunNum == null)
                {
                    sb.Append("puts 'This satellite has no Sun/eclipse telemetry.'\n");
                    return sb.ToString();
                }
                sb.Append("WARP = 20   # simulation speed during the wait (1 = real time)\nPOLL = 5\n\n");
                sb.Append("puts \"🌑 #{TARGET} eclipse pass\"\n");
                sb.Append("puts '  Eclipses are real here: the orbit decides when the Earth hides the Sun.'\n");
                sb.Append("old_warp = tlm(\"#{TARGET} SIM_STATUS WARP\").to_f\n");
                sb.Append("cmd(\"#{TARGET} SIM_SET_WARP with WARP #{WARP}\")\n");
                sb.Append("puts \"  Simulation speed x#{WARP} (restored at the end)\"\n\n");
                sb.Append("def in_sun?\n  tlm(\"" + sunNum + "\").to_f > 0.5\nend\n\n");
                sb.Append("def line(tag)\n  s = \"  #{tag} MET #{met.round} s\"\n");
                if (gen != null) sb.Append($"  s += \" | solar #{{fmt(tlm(\"{gen}\"), 'W', 1)}}\"\n");
                if (net != null) sb.Append($"  s += \" | net #{{fmt(tlm(\"{net}\"), 'W', 1)}}\"\n");
                if (soc != null) sb.Append($"  s += \" | battery #{{fmt(tlm(\"{soc}\"), '%', 1)}}\"\n");
                if (temp != null) sb.Append($"  s += \" | T #{{fmt(tlm(\"{temp}\"), 'C', 1)}}\"\n");
                sb.Append("  puts s\nend\n\n");
                sb.Append("puts '\\n☀️  Waiting for eclipse entry...' if in_sun?\n");
                sb.Append("limit = met + 2 * 86400\nwhile in_sun? && met < limit\n  line('☀️ ')\n  wait(POLL)\nend\n");
                sb.Append($"soc0 = {(soc != null ? $"tlm(\"{soc}\")" : "nil")}\n");
                sb.Append("t_in = met\nsoc_min = soc0\n");
                sb.Append($"temp_min = {(temp != null ? $"tlm(\"{temp}\")" : "nil")}\n");
                sb.Append("puts \"\\n🌑 ECLIPSE ENTRY at MET #{t_in.round} s — battery only\"\n");
                sb.Append("while !in_sun? && met < limit\n  line('🌑')\n");
                if (soc != null) sb.Append($"  s = tlm(\"{soc}\"); soc_min = s if num(s) && (soc_min.nil? || s < soc_min)\n  puts '  🚨 battery below 20 %!' if num(s) && s < 20\n");
                if (temp != null) sb.Append($"  t = tlm(\"{temp}\"); temp_min = t if num(t) && (temp_min.nil? || t < temp_min)\n");
                sb.Append("  wait(POLL)\nend\n");
                sb.Append("t_out = met\nputs \"\\n☀️  SUNLIGHT at MET #{t_out.round} s\"\nline('☀️ ')\n");
                sb.Append("cmd(\"#{TARGET} SIM_SET_WARP with WARP #{[old_warp, 1].max}\")\n\n");
                sb.Append("puts \"\\n\" + '═' * 48\nputs '  Eclipse summary'\n");
                sb.Append("puts \"  Duration:          #{((t_out - t_in) / 60.0).round(1)} min\"\n");
                if (soc != null)
                {
                    sb.Append("puts \"  Battery start/min: #{fmt(soc0, '%', 1)} / #{fmt(soc_min, '%', 1)}\"\n");
                    sb.Append("puts \"  Depth of discharge: #{fmt((soc0 && soc_min) ? soc0 - soc_min : nil, '%', 1)}\"\n");
                }
                if (temp != null) sb.Append("puts \"  Coldest temperature: #{fmt(temp_min, 'C', 1)}\"\n");
                sb.Append("puts '═' * 48\n");
                return sb.ToString();
            }

            // ------------------------------------------------------------------ 4. solar arrays

            public string SolarArrays()
            {
                var sb = new StringBuilder(Header("solar array operations", "Deploy stowed arrays, Sun tracking, power per panel."));
                sb.Append("puts \"☀️  #{TARGET} solar array operations\"\n");
                sb.Append("exit unless wait_for_contact\n");

                var powerKeys = NumKeys(k => k.StartsWith("eps.") && (k.EndsWith(".power") || k.Contains(".panel") || k.EndsWith(".incidence"))).ToList();
                sb.Append("\ndef report\n");
                foreach (string k in powerKeys) sb.Append($"  puts \"  {Q(_num[k].i.Description)}: #{{fmt(tlm(\"{Num(k)}\"), '{Q(_num[k].i.Unit)}', 1)}}\"\n");
                string gen = Num("eps.generation");
                if (gen != null) sb.Append($"  puts \"  Total generation: #{{fmt(tlm(\"{gen}\"), 'W', 1)}}\"\n");
                sb.Append("end\nreport\n");

                foreach (Oc3Command c in Cmds(c => c.SimCommand == "DEPLOY"))
                {
                    string state = Show(c.SimTarget.ToLowerInvariant() + ".deployed");
                    sb.Append($"\nstate = {(state != null ? $"tlm(\"{state}\").to_s" : "'unknown'")}\n");
                    sb.Append("unless state =~ /YES|DEPLOYED/i\n");
                    sb.Append($"  if message_box(\"{c.SimTarget} is #{{state}}. Fire the release now?\", 'Yes', 'No') == 'Yes'\n");
                    sb.Append($"    send_cmd(\"{C(c)}\")\n    wait(5)\n  end\nend\n");
                }

                foreach (string sada in Cmds(c => c.SimTarget.Contains("sada")).Select(c => c.SimTarget).Distinct())
                {
                    Oc3Command on = Cmd(sada, "ON"), off = Cmd(sada, "OFF");
                    string tracking = Show(sada + ".tracking");
                    sb.Append($"\nputs \"\\n  Drive {sada}: #{{{(tracking != null ? $"tlm(\"{tracking}\")" : "'-'")}}}\"\n");
                    sb.Append("choice = message_box('Solar array drive (Sun tracking)', 'Track the Sun', 'Stop', 'Leave')\n");
                    if (on != null) sb.Append($"send_cmd(\"{C(on)}\") if choice == 'Track the Sun'\n");
                    if (off != null) sb.Append($"send_cmd(\"{C(off)}\") if choice == 'Stop'\n");
                }

                Oc3Command adcsMode = Cmd("ADCS", "MODE");
                if (adcsMode != null)
                {
                    sb.Append("\nif message_box('Point the satellite for maximum power (ADCS SUNSAFE)?', 'Yes', 'No') == 'Yes'\n");
                    sb.Append($"  send_cmd(\"{C(adcsMode, "OPTION SUNSAFE")}\")\n  wait_sim(120)\nend\n");
                }
                sb.Append("\nputs \"\\n  After:\"\nreport\n");
                return sb.ToString();
            }

            // ------------------------------------------------------------------ 5. manoeuvre

            public string Maneuver()
            {
                var sb = new StringBuilder(Header("manoeuvre operations",
                    "Pre-checks, engine on, orbit burn (direction and delta-v), burn monitoring, momentum dump, orbit before/after."));
                var sets = ThrusterSets();
                if (sets.Count == 0)
                {
                    sb.Append("puts 'This satellite has no propulsion: add an engine and a tank in the Builder.'\n");
                    return sb.ToString();
                }
                string soc = Num("eps.battery.soc");
                string alt = Num("orbit.altitude");
                string per = Num("orbit.period");
                string inc = Num("orbit.inclination");
                var props = NumKeys(k => k.StartsWith("prop.") && k.EndsWith(".propellant")).Select(Num).ToList();

                sb.Append("puts \"🔥 #{TARGET} manoeuvre operations\"\nexit unless wait_for_contact\n");
                sb.Append("\n# Step 1: pre-manoeuvre checks\nsection('1. Pre-manoeuvre checks')\n");
                if (soc != null) sb.Append($"check_value('Battery', tlm(\"{soc}\"), lo: 60, unit: '%', dec: 1)\n");
                foreach (string p in props) sb.Append($"ok('Propellant', fmt(tlm(\"{p}\"), 'kg', 2))\n");
                string rate = Num("adcs.rate");
                if (rate != null) sb.Append($"check_value('Body rate', tlm(\"{rate}\"), hi: 2, unit: 'deg/s', dec: 3)\n");
                sb.Append("unless $issues.empty?\n  exit unless message_box('Pre-checks found problems. Continue anyway?', 'Continue', 'Abort') == 'Continue'\nend\n");

                sb.Append("\ndef orbit_line\n  s = '  Orbit:'\n");
                if (alt != null) sb.Append($"  s += \" altitude #{{fmt(tlm(\"{alt}\"), 'km', 1)}}\"\n");
                if (per != null) sb.Append($"  s += \" | period #{{fmt(tlm(\"{per}\"), 'min', 2)}}\"\n");
                if (inc != null) sb.Append($"  s += \" | inclination #{{fmt(tlm(\"{inc}\"), 'deg', 3)}}\"\n");
                sb.Append("  puts s\nend\norbit_line\n");

                // choose thruster set
                sb.Append("\n# Step 2: engine\nsection('2. Engine')\n");
                string choices = string.Join(", ", sets.Select(s => $"'{s}'"));
                sb.Append(sets.Count > 1 ? $"engine = combo_box('Which thrusters?', {choices})\n" : $"engine = '{sets[0]}'\n");
                sb.Append("ENGINES = {\n");
                foreach (string s in sets)
                {
                    Oc3Command on = Cmd(s, "ON"), burn = Cmd(s, "BURN"), abort = Cmd(s, "ABORT");
                    string left = Num(s + ".burn_left"), dv = Num(s + ".dv");
                    string param = burn.Params.FirstOrDefault(p => p.Type == Oc3Type.Float64)?.Name ?? "DELTA_V";
                    sb.Append($"  '{s}' => {{ on: {(on != null ? $"\"{C(on)}\"" : "nil")}, burn: \"{_t} {burn.Name}\", dv_param: '{param}', ");
                    sb.Append($"abort: {(abort != null ? $"\"{C(abort)}\"" : "nil")}, left: {(left != null ? $"\"{left}\"" : "nil")}, used: {(dv != null ? $"\"{dv}\"" : "nil")} }},\n");
                }
                sb.Append("}\ne = ENGINES[engine]\nsend_cmd(e[:on]) if e[:on]\n");

                sb.Append("\n# Step 3: the burn\nsection('3. Burn')\n");
                sb.Append("dir = combo_box('Burn direction', 'PROGRADE', 'RETROGRADE', 'NORMAL', 'ANTINORMAL', 'RADIAL_OUT', 'RADIAL_IN')\n");
                sb.Append("dv = ask('Delta-v in m/s (e.g. 0.5)').to_f\n");
                sb.Append("if dv <= 0 || dv > 500\n  puts '  ❌ delta-v must be between 0 and 500 m/s'\n  exit\nend\n");
                sb.Append("used0 = e[:used] ? tlm(e[:used]).to_f : nil\n");
                sb.Append("puts \"  #{engine}: #{dir} #{dv} m/s\"\n");
                sb.Append("exit unless send_cmd(\"#{e[:burn]} with OPTION #{dir}, #{e[:dv_param]} #{dv}\")\n");

                sb.Append("\n# Step 4: follow the burn\nsection('4. Burn progress')\n");
                sb.Append("if e[:left]\n  wait(3)\n  limit = met + 7200\n  while met < limit\n");
                sb.Append("    left = tlm(e[:left]).to_f\n    puts \"  remaining #{left.round(4)} m/s\"\n    break if left <= 1e-6\n");
                sb.Append("    wait(2)\n  end\nend\n");
                sb.Append("puts \"  ✅ applied #{(tlm(e[:used]).to_f - used0).round(4)} m/s\" if e[:used]\n");

                Oc3Command dump = Cmd("ADCS", "DUMP");
                if (dump != null && NumKeys(k => k.StartsWith("adcs.wheels.")).Any())
                {
                    string mom = Num("adcs.wheels.momentum");
                    sb.Append("\n# Step 5: wheel momentum\nsection('5. Reaction wheels')\n");
                    if (mom != null)
                    {
                        sb.Append($"m = tlm(\"{mom}\")\ncheck_value('Wheel momentum', m, hi: 90, unit: '%', dec: 0)\n");
                        sb.Append($"send_cmd(\"{C(dump, "OPTION NOW")}\") if num(m) && m > 50\n");
                    }
                }

                sb.Append("\nsection('6. Result')\nwait(3)\norbit_line\n");
                foreach (string p in props) sb.Append($"ok('Propellant left', fmt(tlm(\"{p}\"), 'kg', 2))\n");
                sb.Append("puts \"\\n  Tip: plan burns visually in the Academy Orbit Simulation, then run maneuver_plan.rb.\"\n");
                return sb.ToString();
            }
        }

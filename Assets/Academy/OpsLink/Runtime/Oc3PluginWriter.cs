using System;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;

namespace Academy.OpsLink
{
    /// <summary>
    /// Writes an OpenC3 COSMOS plugin source tree (plugin.txt, gemspec, target with
    /// cmd/tlm definitions and Telemetry Viewer screens) for an <see cref="Oc3Dictionary"/>.
    /// The satellite itself is the Unity simulator, reached over TCP with a 4-byte length prefix.
    /// </summary>
    public static class Oc3PluginWriter
    {
        public sealed class Options
        {
            public string LinkHost = "host.docker.internal";
            public int LinkPort = 7779;
        }

        static readonly CultureInfo Inv = CultureInfo.InvariantCulture;

        public static string GemName(Oc3Dictionary d) => "openc3-cosmos-" + d.TargetName.ToLowerInvariant().Replace('_', '-');

        /// <summary>Writes the plugin into <paramref name="dir"/> (emptied first) and returns the gem name.</summary>
        public static string Write(Oc3Dictionary d, string dir, Options opt = null)
        {
            opt = opt ?? new Options();
            if (Directory.Exists(dir)) Directory.Delete(dir, true);
            string target = Path.Combine(dir, "targets", d.TargetName);
            Directory.CreateDirectory(Path.Combine(target, "cmd_tlm"));
            Directory.CreateDirectory(Path.Combine(target, "screens"));

            string gem = GemName(d);
            File.WriteAllText(Path.Combine(dir, gem + ".gemspec"), Gemspec(d, gem));
            File.WriteAllText(Path.Combine(dir, "plugin.txt"), PluginTxt(d, opt));
            File.WriteAllText(Path.Combine(target, "target.txt"), TargetTxt());
            File.WriteAllText(Path.Combine(target, "cmd_tlm", "cmd.txt"), CmdTxt(d));
            File.WriteAllText(Path.Combine(target, "cmd_tlm", "tlm.txt"), TlmTxt(d));
            foreach (Oc3TlmPacket p in d.Telemetry)
                File.WriteAllText(Path.Combine(target, "screens", p.Name.ToLowerInvariant() + ".txt"), PacketScreen(d, p));
            File.WriteAllText(Path.Combine(target, "screens", "mission_overview.txt"), OverviewScreen(d));
            return gem;
        }

        static string Gemspec(Oc3Dictionary d, string gem)
        {
            string version = "1.0." + DateTime.UtcNow.ToString("yyyyMMddHHmmss", Inv);
            return
$@"# Generated by Satellite Academy (OpsLink). Do not edit by hand.
Gem::Specification.new do |s|
  s.name        = '{gem}'
  s.summary     = 'Satellite Academy: {Q(d.SatelliteName)}'
  s.description = 'Command and telemetry for the satellite built in the Satellite Academy Builder.'
  s.license     = 'MIT'
  s.authors     = ['Satellite Academy']
  s.email       = ['academy@localhost']
  s.homepage    = 'https://openc3.com'
  s.platform    = Gem::Platform::RUBY
  s.version     = '{version}'
  s.files       = Dir.glob('targets/**/*') + %w(plugin.txt)
end
";
        }

        static string PluginTxt(Oc3Dictionary d, Options o) =>
$@"# Generated by Satellite Academy (OpsLink). Do not edit by hand.
# The spacecraft is the Unity simulator; OpenC3 connects to it as a TCP client.
TARGET {d.TargetName} {d.TargetName}

INTERFACE {d.TargetName}_INT tcpip_client_interface.rb {o.LinkHost} {o.LinkPort} {o.LinkPort} 10.0 nil LENGTH 0 32 0 1 BIG_ENDIAN 0 nil nil true
  MAP_TARGET {d.TargetName}
  RECONNECT_DELAY 2.0
  # Every Academy satellite uses the same simulator port; only the one being flown is connected (by OpsLink).
  DONT_CONNECT
";

        static string TargetTxt() =>
@"# Generated by Satellite Academy (OpsLink).
LANGUAGE ruby
IGNORE_PARAMETER LENGTH
IGNORE_PARAMETER CMD_ID
IGNORE_ITEM LENGTH
IGNORE_ITEM PKT_ID
IGNORE_ITEM TIMESEC
IGNORE_ITEM TIMEUS
";

        static string CmdTxt(Oc3Dictionary d)
        {
            var sb = new StringBuilder("# Generated by Satellite Academy (OpsLink). Do not edit by hand.\n\n");
            foreach (Oc3Command c in d.Commands)
            {
                sb.Append($"COMMAND {d.TargetName} {c.Name} BIG_ENDIAN \"{Q(c.Description)}\"\n");
                sb.Append("  APPEND_PARAMETER LENGTH 32 UINT MIN MAX 0 \"Packet length (filled by the link)\"\n");
                sb.Append($"  APPEND_ID_PARAMETER CMD_ID 16 UINT MIN MAX {c.Id} \"Command id\"\n");
                foreach (Oc3Param p in c.Params)
                {
                    switch (p.Type)
                    {
                        case Oc3Type.UInt8Enum:
                            sb.Append($"  APPEND_PARAMETER {p.Name} 8 UINT 0 {Math.Max(0, p.States.Length - 1)} 0 \"{Q(p.Description)}\"\n");
                            for (int i = 0; i < p.States.Length; i++)
                                sb.Append($"    STATE {Oc3Dictionary.Sanitize(p.States[i], "S" + i)} {i}\n");
                            break;
                        case Oc3Type.String:
                            sb.Append($"  APPEND_PARAMETER {p.Name} {p.StringBytes * 8} STRING \"\" \"{Q(p.Description)}\"\n");
                            if (c.SimTarget != null) sb.Append("    REQUIRED\n");
                            break;
                        default:
                            double def = c.Id == Oc3Dictionary.IdSimWarp ? 1 : 0;
                            sb.Append($"  APPEND_PARAMETER {p.Name} 64 FLOAT MIN MAX {Oc3Dictionary.FormatNumber(def)} \"{Q(p.Description)}\"\n");
                            if (c.SimTarget != null) sb.Append("    REQUIRED\n");
                            break;
                    }
                }
                sb.Append('\n');
            }
            return sb.ToString();
        }

        static string TlmTxt(Oc3Dictionary d)
        {
            var sb = new StringBuilder("# Generated by Satellite Academy (OpsLink). Do not edit by hand.\n\n");
            foreach (Oc3TlmPacket p in d.Telemetry)
            {
                sb.Append($"TELEMETRY {d.TargetName} {p.Name} BIG_ENDIAN \"{Q(p.Description)}\"\n");
                sb.Append("  APPEND_ITEM LENGTH 32 UINT \"Packet length\"\n");
                sb.Append($"  APPEND_ID_ITEM PKT_ID 16 UINT {p.Id} \"Packet id\"\n");
                sb.Append("  APPEND_ITEM TIMESEC 32 UINT \"Simulation time, Unix seconds\"\n");
                sb.Append("  APPEND_ITEM TIMEUS 32 UINT \"Simulation time, microseconds\"\n");
                sb.Append("  ITEM PACKET_TIME 0 0 DERIVED \"Simulation time\"\n");
                sb.Append("    READ_CONVERSION unix_time_conversion.rb TIMESEC TIMEUS\n");
                foreach (Oc3Item i in p.Items)
                {
                    if (i.Type == Oc3Type.String)
                    {
                        sb.Append($"  APPEND_ITEM {i.Name} {i.StringBytes * 8} STRING \"{Q(i.Description)}\"\n");
                        continue;
                    }
                    sb.Append($"  APPEND_ITEM {i.Name} 64 FLOAT \"{Q(i.Description)}\"\n");
                    if (!string.IsNullOrWhiteSpace(i.Unit))
                        sb.Append($"    UNITS \"{Q(i.Unit)}\" \"{Q(i.Unit)}\"\n");
                    sb.Append($"    FORMAT_STRING \"%.{Math.Min(i.Decimals, 6)}f\"\n");
                    if (!double.IsNaN(i.Low) || !double.IsNaN(i.High))
                    {
                        string lo = double.IsNaN(i.Low) ? "-1e30" : Oc3Dictionary.FormatNumber(i.Low);
                        string hi = double.IsNaN(i.High) ? "1e30" : Oc3Dictionary.FormatNumber(i.High);
                        sb.Append($"    LIMITS DEFAULT 1 ENABLED {lo} {lo} {hi} {hi}\n");
                    }
                }
                sb.Append('\n');
            }
            return sb.ToString();
        }

        static string PacketScreen(Oc3Dictionary d, Oc3TlmPacket p)
        {
            var sb = new StringBuilder();
            sb.Append("SCREEN AUTO AUTO 1.0\n");
            sb.Append($"TITLE \"{Q(d.SatelliteName)} - {Q(p.Description)}\"\n");
            sb.Append("VERTICAL\n");
            sb.Append($"  LABELVALUE {d.TargetName} {p.Name} PACKET_TIMEFORMATTED WITH_UNITS 28\n");
            foreach (Oc3Item i in p.Items)
                sb.Append($"  LABELVALUE {d.TargetName} {p.Name} {i.Name} WITH_UNITS {(i.Type == Oc3Type.String ? 40 : 16)}\n");
            sb.Append("END\n");
            return sb.ToString();
        }

        static string OverviewScreen(Oc3Dictionary d)
        {
            var sb = new StringBuilder();
            sb.Append("SCREEN AUTO AUTO 1.0\n");
            sb.Append($"TITLE \"{Q(d.SatelliteName)} - Mission overview\"\n");
            var link = d.TlmById(Oc3Dictionary.IdSimStatus);
            var ack = d.TlmById(Oc3Dictionary.IdCmdAck);
            sb.Append("HORIZONTAL\n");
            sb.Append("  VERTICALBOX \"Ground link\"\n");
            foreach (Oc3Item i in link.Items)
                sb.Append($"    LABELVALUE {d.TargetName} {link.Name} {i.Name} WITH_UNITS 14\n");
            sb.Append("  END\n");
            sb.Append("  VERTICALBOX \"Last command\"\n");
            foreach (Oc3Item i in ack.Items)
                sb.Append($"    LABELVALUE {d.TargetName} {ack.Name} {i.Name} WITH_UNITS 40\n");
            sb.Append("  END\n");
            sb.Append("END\n");

            var subsystems = d.Telemetry.Where(p => p.Id < Oc3Dictionary.IdSimStatus).ToList();
            for (int row = 0; row < subsystems.Count; row += 3)
            {
                sb.Append("HORIZONTAL\n");
                foreach (Oc3TlmPacket p in subsystems.Skip(row).Take(3))
                {
                    sb.Append($"  VERTICALBOX \"{Q(p.Description)}\"\n");
                    foreach (Oc3Item i in p.Items.Where(x => x.Type != Oc3Type.String).Take(10))
                        sb.Append($"    LABELVALUE {d.TargetName} {p.Name} {i.Name} WITH_UNITS 14\n");
                    sb.Append("  END\n");
                }
                sb.Append("END\n");
            }
            return sb.ToString();
        }

        static string Q(string s) => (s ?? "").Replace("\"", "'").Replace("\n", " ").Replace("\r", " ");
    }
}
